import { PDFDocument, PDFFont, PDFPage, StandardFonts, rgb } from "pdf-lib";
import { drawAgencyLogo, embedAgencyLogo } from "./agency-logo";

export type BillingInvoicePdfData = {
  agencyName: string;
  agencyLogoUrl?: string | null;
  invoiceId: string;
  planCode: string;
  status: string;
  currency: string;
  amount: number;
  paymentMethod: string;
  paymentReference: string;
  paidAt?: string | null;
  periodStart?: string | null;
  periodEnd?: string | null;
};

const ink = rgb(0.04, 0.09, 0.16);
const muted = rgb(0.38, 0.43, 0.5);
const green = rgb(0.02, 0.64, 0.45);
const pale = rgb(0.95, 0.97, 0.98);
const safe = (value: string) => value.replace(/[–—]/g, "-").replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E\xA0-\xFF]/g, "?");
const money = (currency: string, amount: number) => `${currency.toUpperCase()} ${amount.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const date = (value?: string | null) => value ? new Intl.DateTimeFormat("en", { dateStyle: "medium" }).format(new Date(value)) : "-";

function drawText(page: PDFPage, font: PDFFont, value: string, x: number, y: number, size = 10, color = ink) {
  page.drawText(safe(value), { x, y, size, font, color });
}

export async function createBillingInvoicePdf(data: BillingInvoicePdfData) {
  const pdf = await PDFDocument.create();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const page = pdf.addPage([595, 842]);
  const logo = await embedAgencyLogo(pdf, data.agencyLogoUrl);
  page.drawRectangle({ x: 0, y: 750, width: 595, height: 92, color: ink });
  drawAgencyLogo(page, logo);
  const brandX = logo ? 116 : 48;
  drawText(page, bold, data.agencyName.toUpperCase(), brandX, 805, 17, rgb(1, 1, 1));
  drawText(page, regular, "POWERED BY DIINI AI", brandX, 783, 9, green);
  drawText(page, bold, "SUBSCRIPTION INVOICE", 350, 799, 14, rgb(1, 1, 1));
  drawText(page, regular, `Invoice: ${data.invoiceId.slice(0, 8).toUpperCase()}`, 350, 779, 9, rgb(0.75, 0.8, 0.86));

  drawText(page, bold, "BILLED TO", 48, 708, 9, green);
  drawText(page, bold, data.agencyName, 48, 684, 15);
  drawText(page, regular, `Plan: ${data.planCode.toUpperCase()}`, 48, 663, 10, muted);
  drawText(page, bold, "PAYMENT STATUS", 365, 708, 9, green);
  drawText(page, bold, data.status.toUpperCase(), 365, 682, 15, green);
  drawText(page, regular, `Paid: ${date(data.paidAt)}`, 365, 662, 10, muted);

  page.drawRectangle({ x: 48, y: 510, width: 499, height: 112, color: pale });
  drawText(page, regular, "DESCRIPTION", 64, 590, 8, muted);
  drawText(page, bold, `${data.planCode.toUpperCase()} subscription`, 64, 565, 13);
  drawText(page, regular, `${date(data.periodStart)} - ${date(data.periodEnd)}`, 64, 542, 10, muted);
  drawText(page, regular, "AMOUNT", 405, 590, 8, muted);
  drawText(page, bold, money(data.currency, data.amount), 405, 562, 13);

  drawText(page, bold, "PAYMENT DETAILS", 48, 460, 12);
  drawText(page, regular, "Payment method", 48, 425, 9, muted);
  drawText(page, bold, data.paymentMethod.replaceAll("_", " ").toUpperCase(), 48, 402, 12);
  drawText(page, regular, "Transaction reference", 300, 425, 9, muted);
  drawText(page, bold, data.paymentReference, 300, 402, 12);

  page.drawLine({ start: { x: 48, y: 345 }, end: { x: 547, y: 345 }, thickness: 0.7, color: rgb(0.82, 0.85, 0.88) });
  drawText(page, bold, "TOTAL PAID", 340, 305, 11);
  drawText(page, bold, money(data.currency, data.amount), 435, 305, 13, green);
  drawText(page, regular, "This invoice confirms a manually verified payment.", 48, 265, 9, muted);
  drawText(page, regular, "Keep the transaction reference for your records.", 48, 247, 9, muted);
  page.drawLine({ start: { x: 48, y: 72 }, end: { x: 547, y: 72 }, thickness: 0.7, color: rgb(0.82, 0.85, 0.88) });
  drawText(page, regular, "Generated by DIINI AI Real Estate", 365, 50, 9, muted);
  return pdf.save();
}

